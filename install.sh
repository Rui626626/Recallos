#!/bin/sh
# Install RecallOS: verify the environment, create a `recall` launcher, and
# install the bundled Skill where DSH will find it.
#
# Deliberately conservative. It does NOT copy the project anywhere, does NOT
# install any package, and does NOT touch your PATH unless you pass --add-to-path.
#
#   ./install.sh                  # verify + launcher + Skill
#   ./install.sh --add-to-path    # also append the bin dir to your shell rc file
#   ./install.sh --skip-doctor
#   ./install.sh --skip-skill     # leave the Skill alone
#
# The Skill goes into the **user-level** root ($DSH_HOME/skills) so it is
# available in every DSH session, not only ones started in this directory.
#
# Messages are in English so the script stays readable in any locale.

set -eu

BIN_DIR=""
ADD_TO_PATH=0
SKIP_DOCTOR=0
SKIP_SKILL=0

while [ $# -gt 0 ]; do
    case "$1" in
        --bin-dir)      BIN_DIR="$2"; shift 2 ;;
        --add-to-path)  ADD_TO_PATH=1; shift ;;
        --skip-doctor)  SKIP_DOCTOR=1; shift ;;
        --skip-skill)   SKIP_SKILL=1; shift ;;
        -h|--help)
            sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'
            exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
done

step()  { printf '==> %s\n' "$1"; }
ok()    { printf '  ok  %s\n' "$1"; }
warn()  { printf '  warn %s\n' "$1"; }
fail()  { printf '  FAIL %s\n' "$1" >&2; }

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
CLI="$SCRIPT_DIR/bin/recall.py"

if [ ! -f "$CLI" ]; then
    fail "bin/recall.py not found next to this script ($SCRIPT_DIR)"
    exit 2
fi

# --------------------------------------------------------------------- Python
step "Looking for Python 3.9+"

PYTHON=""
for candidate in python3 python python3.13 python3.12 python3.11 python3.10 python3.9; do
    if command -v "$candidate" >/dev/null 2>&1; then
        version=$("$candidate" -c 'import sys; print("%d.%d.%d" % sys.version_info[:3])' 2>/dev/null || true)
        [ -n "$version" ] || continue
        major=${version%%.*}
        rest=${version#*.}
        minor=${rest%%.*}
        if [ "$major" -gt 3 ] || { [ "$major" -eq 3 ] && [ "$minor" -ge 9 ]; }; then
            PYTHON=$(command -v "$candidate")
            PY_VERSION="$version"
            break
        fi
    fi
done

if [ -z "$PYTHON" ]; then
    fail "No Python 3.9+ found. Install one and re-run."
    exit 2
fi
ok "python $PY_VERSION  ($PYTHON)"

# ------------------------------------------------------------------------ CLI
step "Checking the command line"
if ! version=$("$PYTHON" "$CLI" --version 2>&1); then
    fail "recall.py --version failed: $version"
    exit 1
fi
ok "$version"

step "Creating the layout (idempotent; never overwrites)"
"$PYTHON" "$CLI" init

if [ "$SKIP_DOCTOR" -eq 0 ]; then
    step "Running doctor"
    if ! "$PYTHON" "$CLI" doctor; then
        warn "doctor did not pass; fix the items above before relying on it."
    fi
fi

# ------------------------------------------------------------------- launcher
step "Creating the launcher"

if [ -z "$BIN_DIR" ]; then
    BIN_DIR="$HOME/.local/bin"
fi
mkdir -p "$BIN_DIR"

LAUNCHER="$BIN_DIR/recall"
cat > "$LAUNCHER" <<EOF
#!/bin/sh
# Generated by RecallOS install.sh -- safe to delete.
PYTHONIOENCODING=utf-8 exec "$PYTHON" "$CLI" "\$@"
EOF
chmod +x "$LAUNCHER"
ok "$LAUNCHER"

# ----------------------------------------------------------------- skill
#
# User-level so the Skill is visible in every DSH session, not only ones started
# inside this directory. Path detection lives in `recall.py install-skill`
# (Python) instead of being duplicated here — two copies of that rule drift.
if [ "$SKIP_SKILL" -eq 0 ]; then
    step "Installing the Skill where DSH will find it"
    if ! "$PYTHON" "$CLI" install-skill --user; then
        warn "could not install the Skill automatically."
        printf '     The command line still works. To retry by hand:\n'
        printf '       %s %s install-skill --user\n' "$PYTHON" "$CLI"
    fi
fi

# ----------------------------------------------------------------------- PATH
case ":${PATH:-}:" in
    *":$BIN_DIR:"*) already=1 ;;
    *) already=0 ;;
esac

if [ "$already" -eq 1 ]; then
    ok "$BIN_DIR is already on your PATH"
elif [ "$ADD_TO_PATH" -eq 1 ]; then
    RC=""
    case "${SHELL:-}" in
        */zsh)  RC="$HOME/.zshrc" ;;
        */bash) RC="$HOME/.bashrc" ;;
    esac
    if [ -z "$RC" ]; then
        warn "Could not detect your shell rc file; add this line yourself:"
        printf '     export PATH="%s:$PATH"\n' "$BIN_DIR"
    elif grep -qs "RecallOS" "$RC" 2>/dev/null; then
        ok "$RC already mentions RecallOS; not touching it again"
    else
        printf '\n# Added by RecallOS install.sh\nexport PATH="%s:$PATH"\n' "$BIN_DIR" >> "$RC"
        ok "Appended $BIN_DIR to PATH in $RC (open a new shell to use it)"
        printf '     to undo: remove those two lines from %s\n' "$RC"
    fi
else
    warn "$BIN_DIR is NOT on your PATH (nothing was changed)."
    printf '     To use the `recall` command everywhere, add this to your shell rc:\n'
    printf '     export PATH="%s:$PATH"\n' "$BIN_DIR"
fi

printf '\nRecallOS is ready.\n'
printf '  from anywhere:  recall doctor\n'
printf '  right now:      %s %s search "<query>"\n' "$PYTHON" "$CLI"
