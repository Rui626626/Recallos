<#
.SYNOPSIS
    Install RecallOS: verify the environment and create a `recall` launcher.

.DESCRIPTION
    Deliberately conservative. It does NOT copy the project anywhere, does NOT
    install any package, and does NOT touch your PATH unless you explicitly ask
    with -AddToPath.

    What it does:
      1. finds a usable Python (3.9+) and checks it
      2. runs `recall.py --version` to prove the CLI starts
      3. runs `init` (idempotent: never overwrites an existing file)
      4. runs `doctor` and reports the result
      5. writes a `recall.cmd` launcher into the chosen bin directory

    Messages are in English on purpose: Windows PowerShell 5.1 decodes a .ps1
    without a BOM as ANSI, so non-ASCII text in this file would be garbled for
    anyone running it under 5.1.

.PARAMETER BinDir
    Where to put the launcher. Defaults to %LOCALAPPDATA%\RecallOS\bin.

.PARAMETER AddToPath
    Append BinDir to your *user* PATH. Off by default; this script prints the
    exact command instead so you can decide.

.PARAMETER SkipDoctor
    Skip the doctor run (useful in CI where you only want the launcher).

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File install.ps1
    powershell -ExecutionPolicy Bypass -File install.ps1 -AddToPath
#>

[CmdletBinding()]
param(
    [string]$BinDir = "",
    [switch]$AddToPath,
    [switch]$SkipDoctor,
    [switch]$SkipSkill
)

$ErrorActionPreference = "Stop"

function Write-Step($text) { Write-Host "==> $text" -ForegroundColor Cyan }
function Write-Ok($text)   { Write-Host "  ok  $text" -ForegroundColor Green }
function Write-Warn2($text){ Write-Host "  warn $text" -ForegroundColor Yellow }
function Write-Err2($text) { Write-Host "  FAIL $text" -ForegroundColor Red }

$RepoRoot = Split-Path -Parent (Resolve-Path $PSCommandPath).Path
$Cli = Join-Path $RepoRoot "bin\recall.py"

if (-not (Test-Path $Cli)) {
    Write-Err2 "bin\recall.py not found next to this script ($RepoRoot)."
    exit 2
}

# --------------------------------------------------------------------- Python
Write-Step "Looking for Python 3.9+"

$candidates = @()
foreach ($name in @("python", "python3", "py")) {
    $cmd = Get-Command $name -ErrorAction SilentlyContinue
    if ($cmd) { $candidates += $cmd.Source }
}
if ($candidates.Count -eq 0) {
    Write-Err2 "No python on PATH. Install Python 3.9+ and re-run."
    exit 2
}

$Python = $null
$PythonVersion = $null
foreach ($exe in $candidates) {
    try {
        $raw = & $exe -c "import sys; print('%d.%d.%d' % sys.version_info[:3])" 2>$null
    } catch { continue }
    if (-not $raw) { continue }
    $parts = $raw.Trim().Split(".")
    if ($parts.Count -lt 2) { continue }
    $major = [int]$parts[0]; $minor = [int]$parts[1]
    if ($major -gt 3 -or ($major -eq 3 -and $minor -ge 9)) {
        $Python = $exe
        $PythonVersion = $raw.Trim()
        break
    }
}

if (-not $Python) {
    Write-Err2 "Found python, but none is 3.9 or newer."
    exit 2
}
Write-Ok "python $PythonVersion  ($Python)"

# ------------------------------------------------------------------------ CLI
Write-Step "Checking the command line"

$version = & $Python $Cli --version 2>&1
if ($LASTEXITCODE -ne 0) {
    Write-Err2 "recall.py --version failed: $version"
    exit 1
}
Write-Ok "$($version -join ' ')"

Write-Step "Creating the layout (idempotent; never overwrites)"
& $Python $Cli init
if ($LASTEXITCODE -ne 0) {
    Write-Err2 "init failed"
    exit 1
}

if (-not $SkipDoctor) {
    Write-Step "Running doctor"
    & $Python $Cli doctor
    if ($LASTEXITCODE -ne 0) {
        Write-Warn2 "doctor did not pass; fix the items above before relying on it."
    }
}

# ------------------------------------------------------------------- launcher
Write-Step "Creating the launcher"

if ([string]::IsNullOrWhiteSpace($BinDir)) {
    $BinDir = Join-Path $env:LOCALAPPDATA "RecallOS\bin"
}
New-Item -ItemType Directory -Force -Path $BinDir | Out-Null

$launcher = Join-Path $BinDir "recall.cmd"
$body = @"
@echo off
rem Generated by RecallOS install.ps1 -- safe to delete.
set PYTHONIOENCODING=utf-8
"$Python" "$Cli" %*
"@
Set-Content -Path $launcher -Value $body -Encoding ASCII
Write-Ok $launcher

# ----------------------------------------------------------------- skill
#
# Install the bundled Skill into the **user-level** root so it is available in
# every DSH session, not just sessions started inside this directory. That is
# the whole point: without it the assistant has no idea RecallOS exists and the
# user has to type commands by hand.
#
# The path detection lives in `recall.py install-skill` (Python) rather than
# being reimplemented here — two copies of that rule would drift.
if (-not $SkipSkill) {
    Write-Step "Installing the Skill where DSH will find it"
    & $Python $Cli install-skill --user
    if ($LASTEXITCODE -ne 0) {
        Write-Warn2 "could not install the Skill automatically."
        Write-Host "     The command line still works. To retry by hand:" -ForegroundColor DarkGray
        Write-Host "       $Python `"$Cli`" install-skill --user" -ForegroundColor DarkGray
    }
}

# ----------------------------------------------------------------------- PATH
$userPath = [Environment]::GetEnvironmentVariable("Path", "User")
$already = $false
if ($userPath) {
    foreach ($p in $userPath.Split(";")) {
        if ($p.Trim().TrimEnd("\") -ieq $BinDir.TrimEnd("\")) { $already = $true; break }
    }
}

if ($already) {
    Write-Ok "$BinDir is already on your user PATH"
} elseif ($AddToPath) {
    $newPath = if ([string]::IsNullOrWhiteSpace($userPath)) { $BinDir } else { "$userPath;$BinDir" }
    [Environment]::SetEnvironmentVariable("Path", $newPath, "User")
    Write-Ok "Added $BinDir to your user PATH (open a new terminal to use it)"
    Write-Host "     to undo:" -ForegroundColor DarkGray
    Write-Host "     [Environment]::SetEnvironmentVariable('Path','$userPath','User')" -ForegroundColor DarkGray
} else {
    Write-Warn2 "$BinDir is NOT on your PATH (nothing was changed)."
    Write-Host "     To use the 'recall' command everywhere, either re-run with -AddToPath," -ForegroundColor DarkGray
    Write-Host "     or add this to your user PATH yourself:" -ForegroundColor DarkGray
    Write-Host "     $BinDir" -ForegroundColor DarkGray
}

Write-Host ""
Write-Host "RecallOS is ready." -ForegroundColor Green
Write-Host "  from anywhere:  recall doctor"
Write-Host "  right now:      & `"$Python`" `"$Cli`" search `"<query>`""
